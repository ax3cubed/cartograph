//! XS-18: a `.proto` is a contract of `RPC` operations, and a Go server and a TypeScript client
//! generated from it are linked through the generated code alone: the client's call names the rpc,
//! the server's `Register…Server` serves it, and the proto is the operation both meet in.

use std::path::Path;

use cartograph_facts::FactCache;
use cartograph_git::fixture::Fixture;
use cartograph_index::structure::ServiceSpec;
use cartograph_index::sync::{SyncOptions, SyncOutcome, Workspace, sync};
use cartograph_index::timeline::RepoSpec;
use cartograph_store::Index;

const COMPOSE: &str = "services:\n  orders:\n    build: ./orders\n  web:\n    build: ./web\n";
const PROTO: &str = r#"syntax = "proto3";
package acme.orders.v1;

import "acme/common/v1/money.proto";
import "third/lib.proto";
import "acme/missing/v1/gone.proto";
import "../../../../etc/passwd.proto";
import "google/protobuf/timestamp.proto";

service Orders {
  rpc Get(GetRequest) returns (Order);
  rpc Watch(GetRequest) returns (stream Order);
}

message GetRequest { string id = 1; }
message Order { string id = 1; acme.common.v1.Money total = 2; }
"#;
const MONEY: &str =
    "syntax = \"proto3\";\npackage acme.common.v1;\nmessage Money { int64 units = 1; }\n";
const LIB: &str = "syntax = \"proto3\";\npackage third;\nmessage Lib { string a = 1; }\n";
const BUF: &str = "version: v2\nmodules:\n  - path: proto\n  - path: shared\n";
const GO_MOD: &str = "module example.com/orders\n\ngo 1.22\n";
const GRPC_GO: &str = r#"// Code generated by protoc-gen-go-grpc. DO NOT EDIT.
package pb

const (
	Orders_Get_FullMethodName   = "/acme.orders.v1.Orders/Get"
	Orders_Watch_FullMethodName = "/acme.orders.v1.Orders/Watch"
)

func RegisterOrdersServer(s grpc.ServiceRegistrar, srv OrdersServer) {
	s.RegisterService(&Orders_ServiceDesc, srv)
}

var Orders_ServiceDesc = grpc.ServiceDesc{
	ServiceName: "acme.orders.v1.Orders",
	HandlerType: (*OrdersServer)(nil),
	Metadata:    "acme/orders/v1/orders.proto",
}
"#;
const MAIN_GO: &str = r#"package main

import "example.com/orders/pb"

func main() {
	s := grpc.NewServer()
	pb.RegisterOrdersServer(s, &server{})
}
"#;
const CONNECT_TS: &str = r#"// @generated by protoc-gen-connect-es v1.4.2 with parameter "target=ts"
import { GetRequest, Order } from "./orders_pb.js";
import { MethodKind } from "@bufbuild/protobuf";

export const Orders = {
  typeName: "acme.orders.v1.Orders",
  methods: {
    get: { name: "Get", I: GetRequest, O: Order, kind: MethodKind.Unary },
    watch: { name: "Watch", I: GetRequest, O: Order, kind: MethodKind.ServerStreaming },
  },
} as const;
"#;
const PAGE_TS: &str = r#"import { createPromiseClient } from "@connectrpc/connect";
import { Orders } from "./gen/orders_connect";

const client = createPromiseClient(Orders, transport);

export function show(id: string) {
  return client.get({ id });
}
"#;

fn workspace(f: &Fixture, dir: &Path) -> Workspace {
    let svc = |name: &str| ServiceSpec {
        name: name.into(),
        repo: "repo".into(),
        path: Some(name.into()),
    };
    Workspace {
        dir: dir.to_owned(),
        repos: vec![RepoSpec {
            name: "repo".into(),
            path: f.dir.clone(),
            ..Default::default()
        }],
        services: vec![svc("orders"), svc("web")],
        ..Default::default()
    }
}

fn run(w: &Workspace, cache: &mut FactCache) {
    match sync(w, &SyncOptions::default(), cache).unwrap() {
        SyncOutcome::Synced(_) => {}
        SyncOutcome::AlreadyRunning => panic!("nothing else is running"),
    }
}

fn fixture(d: &Path) -> Fixture {
    let mut f = Fixture::init(&d.join("repo"));
    f.write("docker-compose.yml", COMPOSE);
    f.write("orders/go.mod", GO_MOD);
    f.write("web/package.json", r#"{"name":"web"}"#);
    f.write("api/buf.yaml", BUF);
    f.write("api/proto/acme/orders/v1/orders.proto", PROTO);
    f.write("api/proto/acme/common/v1/money.proto", MONEY);
    f.write("api/shared/third/lib.proto", LIB);
    f.commit("api: the protos");
    f.write("orders/pb/orders_grpc.pb.go", GRPC_GO);
    f.write("orders/main.go", MAIN_GO);
    f.write("web/src/gen/orders_connect.ts", CONNECT_TS);
    f.write("web/src/page.ts", PAGE_TS);
    f.commit("orders and web: generated code and its users");
    f
}

fn rows(w: &Workspace, sql: &str) -> Vec<String> {
    let ix = Index::open_read(&w.index_path()).unwrap();
    let mut st = ix.conn.prepare(sql).unwrap();
    let n = st.column_count();
    st.query_map([], |r| {
        (0..n)
            .map(|i| {
                Ok(match r.get_ref(i)? {
                    cartograph_store::rusqlite::types::ValueRef::Null => "-".to_owned(),
                    cartograph_store::rusqlite::types::ValueRef::Integer(i) => i.to_string(),
                    cartograph_store::rusqlite::types::ValueRef::Text(t) => {
                        String::from_utf8_lossy(t).into_owned()
                    }
                    _ => String::new(),
                })
            })
            .collect::<Result<Vec<_>, _>>()
            .map(|c| c.join(" "))
    })
    .unwrap()
    .map(Result::unwrap)
    .collect()
}

const PATH: &str =
    "(SELECT path FROM file_path p WHERE p.file = n.file ORDER BY from_seq DESC LIMIT 1)";

#[test]
fn a_go_server_and_a_ts_client_of_one_proto_are_linked_exact() {
    let d = tempfile::tempdir().unwrap();
    let f = fixture(d.path());
    let w = workspace(&f, &d.path().join("ws"));
    let mut cache = FactCache::open(&d.path().join("facts.db")).unwrap();
    run(&w, &mut cache);

    // The proto's operations and schemas, with the template the matcher reads.
    assert_eq!(
        rows(
            &w,
            "SELECT o.method, o.path, o.template, o.operation_id, o.summary, o.from_seq FROM operation o ORDER BY o.path"
        ),
        [
            "RPC /acme.orders.v1.Orders/Get RPC /acme.orders.v1.Orders/Get Orders.Get unary 0",
            "RPC /acme.orders.v1.Orders/Watch RPC /acme.orders.v1.Orders/Watch Orders.Watch server stream 0",
        ]
    );
    assert_eq!(
        rows(&w, "SELECT name FROM contract_schema ORDER BY name"),
        ["GetRequest", "Lib", "Money", "Order"]
    );
    // Imports: `third/lib.proto` is found through the buf.yaml module, the missing and the
    // escaping ones are said, the bundled well-known type is neither.
    assert_eq!(
        rows(
            &w,
            "SELECT spec, reason FROM unresolved WHERE fact_kind = 'openapi.ref' ORDER BY spec"
        ),
        [
            "../../../../etc/passwd.proto outside",
            "acme/missing/v1/gone.proto missing"
        ]
    );
    // The caller meets the server through the operation: exact.
    assert_eq!(
        rows(
            &w,
            &format!(
                "SELECT (SELECT {PATH} FROM node n WHERE n.id = l.src), (SELECT {PATH} FROM node n WHERE n.id = l.dst),
                        l.level, (SELECT group_concat(DISTINCT kind) FROM (SELECT kind FROM evidence e WHERE e.link = l.id ORDER BY kind))
                 FROM link l WHERE l.kind = 'http' ORDER BY 1, 2"
            )
        ),
        ["web/src/page.ts orders/main.go exact contract,generated"]
    );
    assert_eq!(
        rows(
            &w,
            "SELECT b.kind, b.template FROM binding b ORDER BY b.kind, b.template"
        ),
        [
            "consumes rpc /acme.orders.v1.Orders/Get",
            "handled_by rpc /acme.orders.v1.Orders/Get",
            "handled_by rpc /acme.orders.v1.Orders/Watch"
        ]
    );

    // A fresh index of the same history says the same.
    let d2 = tempfile::tempdir().unwrap();
    let w2 = workspace(&f, &d2.path().join("ws"));
    let mut cache2 = FactCache::open(&d2.path().join("facts.db")).unwrap();
    run(&w2, &mut cache2);
    let q = "SELECT kind, template FROM binding ORDER BY 1, 2";
    assert_eq!(rows(&w2, q), rows(&w, q));
}
