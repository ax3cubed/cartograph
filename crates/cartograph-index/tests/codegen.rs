//! XS-11: a call through a generated client is a call to the spec operation the generated function
//! spells out. An orval client (TypeScript) and an oapi-codegen client (Go) in two services call
//! the orders service; the links are likely on the spec alone and exact when the operation also
//! matches the server's route. A regenerated client that renames its functions keeps the link.

use std::path::Path;

use cartograph_facts::FactCache;
use cartograph_git::fixture::Fixture;
use cartograph_index::contracts::ContractSpec;
use cartograph_index::structure::ServiceSpec;
use cartograph_index::sync::{SyncOptions, SyncOutcome, Workspace, sync};
use cartograph_index::timeline::RepoSpec;
use cartograph_store::Index;

const COMPOSE: &str = "services:\n  orders:\n    build: ./orders\n  web:\n    build: ./web\n  billing:\n    build: ./billing\n";
const SERVER: &str = "import express from \"express\";\nconst app = express();\n\napp.get(\"/orders/:id\", (req, res) => res.json({}));\napp.get(\"/customers/:id\", (req, res) => res.json({}));\napp.get(\"/ping/:id\", (req, res) => res.send(\"pong\"));\n";
const SPEC: &str = "openapi: 3.0.3
info: {title: Orders}
paths:
  /orders/{id}:
    get: {operationId: getOrder}
  /customers/{id}:
    get: {operationId: getCustomer}
";
// Owned by web, not by the service that serves it: the operation is not the route's.
const WEB_SPEC: &str = "openapi: 3.0.3
info: {title: Ping}
paths:
  /ping/{id}:
    get: {operationId: getPing}
";

fn orval(get_order: &str) -> String {
    format!(
        "/**
 * Generated by orval v7.10.0
 * Do not edit manually.
 * Orders
 * OpenAPI spec version: 1.0.0
 */
import axios from \"axios\";

export const getOrdersAPI = () => {{
  const {get_order} = (id: string) => {{
    return axios.get(`/orders/${{id}}`);
  }};
  const getPing = (id: string) => axios.get(`/ping/${{id}}`);
  return {{ {get_order}, getPing }};
}};
"
    )
}

const PING: &str = "import { getOrdersAPI } from \"./api/orders\";

const { getPing } = getOrdersAPI();

export const ping = (id: string) => getPing(id);
";

fn page(get_order: &str) -> String {
    format!(
        "import {{ getOrdersAPI }} from \"./api/orders\";

const {{ {get_order} }} = getOrdersAPI();

export function show(id: string) {{
  return {get_order}(id);
}}
"
    )
}

const GO_MOD: &str = "module example.com/billing\n\ngo 1.22\n";
const OAPI: &str = "// Package api provides primitives to interact with the openapi HTTP API.
//
// Code generated by github.com/oapi-codegen/oapi-codegen/v2 version v2.4.1 DO NOT EDIT.
package api

func NewGetCustomerRequest(server string, id string) (*http.Request, error) {
	var err error
	operationPath := fmt.Sprintf(\"/customers/%s\", pathParam0)
	req, err := http.NewRequest(\"GET\", queryURL.String(), nil)
	return req, err
}

func (c *Client) GetCustomer(ctx context.Context, id string) (*http.Response, error) {
	req, err := NewGetCustomerRequest(c.Server, id)
	return c.Client.Do(req)
}
";
const MAIN_GO: &str = "package main

import \"example.com/billing/api\"

func main() {
	c := api.NewClient(\"http://orders:8080\")
	c.GetCustomer(ctx, \"7\")
}
";

fn workspace(f: &Fixture, dir: &Path) -> Workspace {
    let svc = |name: &str| ServiceSpec {
        name: name.into(),
        repo: "repo".into(),
        path: Some(name.into()),
    };
    Workspace {
        dir: dir.to_owned(),
        repos: vec![RepoSpec {
            name: "repo".into(),
            path: f.dir.clone(),
            ..Default::default()
        }],
        services: vec![svc("orders"), svc("web"), svc("billing")],
        contracts: vec![ContractSpec {
            path: "web/ping.yaml".into(),
            service: Some("web".into()),
        }],
        ..Default::default()
    }
}

fn run(w: &Workspace, cache: &mut FactCache) {
    match sync(w, &SyncOptions::default(), cache).unwrap() {
        SyncOutcome::Synced(_) => {}
        SyncOutcome::AlreadyRunning => panic!("nothing else is running"),
    }
}

fn fixture(d: &Path) -> Fixture {
    let mut f = Fixture::init(&d.join("repo"));
    f.write("docker-compose.yml", COMPOSE);
    f.write("orders/package.json", r#"{"name":"orders"}"#);
    f.write("web/package.json", r#"{"name":"web"}"#);
    f.write("billing/go.mod", GO_MOD);
    f.write("orders/src/server.ts", SERVER);
    f.write("orders/openapi.yaml", SPEC);
    f.write("web/ping.yaml", WEB_SPEC);
    f.commit("orders: routes and spec");
    f.write("web/src/api/orders.ts", &orval("getOrder"));
    f.write("web/src/page.ts", &page("getOrder"));
    f.write("web/src/ping.ts", PING);
    f.write("billing/api/client.gen.go", OAPI);
    f.write("billing/main.go", MAIN_GO);
    f.commit("web and billing: generated clients and their callers");
    f
}

/// `src -> dst level` for each http link, with the kinds of its evidence.
fn links(w: &Workspace) -> Vec<String> {
    let ix = Index::open_read(&w.index_path()).unwrap();
    let path =
        "(SELECT path FROM file_path p WHERE p.file = n.file ORDER BY from_seq DESC LIMIT 1)";
    let mut st = ix
        .conn
        .prepare(&format!(
            "SELECT (SELECT {path} FROM node n WHERE n.id = l.src), (SELECT {path} FROM node n WHERE n.id = l.dst),
                    l.level, group_concat(DISTINCT e.kind),
                    (SELECT group_concat(from_seq || '-' || coalesce(to_seq, 'open')) FROM interval i WHERE i.link = l.id)
             FROM link l JOIN evidence e ON e.link = l.id WHERE l.kind = 'http'
             GROUP BY l.id ORDER BY 1, 2"
        ))
        .unwrap();
    let mut out: Vec<String> = st
        .query_map([], |r| {
            Ok(format!(
                "{} -> {} {} [{}] {}",
                r.get::<_, String>(0)?,
                r.get::<_, String>(1)?,
                r.get::<_, String>(2)?,
                {
                    let k: String = r.get(3)?;
                    let mut k: Vec<&str> = k.split(',').collect();
                    k.sort_unstable();
                    k.join(",")
                },
                r.get::<_, String>(4)?
            ))
        })
        .unwrap()
        .map(Result::unwrap)
        .collect();
    // The generated files' own calls to a server are links of their own; not what this is about.
    out.retain(|l| !l.contains(".gen.go ->") && !l.starts_with("web/src/api/"));
    out
}

fn aliases(w: &Workspace) -> Vec<String> {
    let ix = Index::open_read(&w.index_path()).unwrap();
    let mut st = ix
        .conn
        .prepare(
            "SELECT a.symbol, o.method || ' ' || o.path, a.from_seq, coalesce(a.to_seq, 'open')
             FROM client_alias a JOIN operation o ON o.id = a.operation
             ORDER BY o.path, a.symbol, a.from_seq",
        )
        .unwrap();
    st.query_map([], |r| {
        Ok(format!(
            "{} {} {}-{}",
            r.get::<_, String>(0)?,
            r.get::<_, String>(1)?,
            r.get::<_, i64>(2)?,
            r.get::<_, rusqlite_value::V>(3)?
        ))
    })
    .unwrap()
    .map(Result::unwrap)
    .collect()
}

/// A column that is an integer or the text `open`.
mod rusqlite_value {
    use cartograph_store::rusqlite::types::{FromSql, FromSqlResult, ValueRef};
    pub struct V(String);
    impl FromSql for V {
        fn column_result(v: ValueRef<'_>) -> FromSqlResult<Self> {
            Ok(V(match v {
                ValueRef::Integer(i) => i.to_string(),
                ValueRef::Text(t) => String::from_utf8_lossy(t).into_owned(),
                _ => String::new(),
            }))
        }
    }
    impl std::fmt::Display for V {
        fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
            f.write_str(&self.0)
        }
    }
}

fn generated_nodes(w: &Workspace) -> Vec<String> {
    let ix = Index::open_read(&w.index_path()).unwrap();
    let mut st = ix
        .conn
        .prepare(
            "SELECT (SELECT path FROM file_path p WHERE p.file = n.file ORDER BY from_seq DESC LIMIT 1) || ' ' || n.generated
             FROM node n WHERE n.generated IS NOT NULL ORDER BY 1",
        )
        .unwrap();
    st.query_map([], |r| r.get(0))
        .unwrap()
        .map(Result::unwrap)
        .collect()
}

#[test]
fn calls_through_an_orval_and_an_oapi_codegen_client_are_linked_with_the_level_rules() {
    let d = tempfile::tempdir().unwrap();
    let f = fixture(d.path());
    let w = workspace(&f, &d.path().join("ws"));
    let mut cache = FactCache::open(&d.path().join("facts.db")).unwrap();
    run(&w, &mut cache);

    assert_eq!(
        links(&w),
        [
            // The operation is the route's too: exact, with the spec as evidence.
            "billing/main.go -> orders/src/server.ts exact [contract,generated,literal] 1-open",
            "web/src/page.ts -> orders/src/server.ts exact [contract,generated,literal] 1-open",
            // The ping operation belongs to web, so it is not the route's: the call stays likely.
            "web/src/ping.ts -> orders/src/server.ts likely [generated,literal] 1-open",
        ]
    );
    let ix = Index::open_read(&w.index_path()).unwrap();
    assert_eq!(
        aliases(&w),
        [
            "GetCustomer get /customers/{id} 1-open",
            "GetCustomerWithResponse get /customers/{id} 1-open",
            "NewGetCustomerRequest get /customers/{id} 1-open",
            "getOrder get /orders/{id} 1-open",
            "getPing get /ping/{id} 1-open",
        ]
    );
    // Flagged on the node, and not a gap of the files parsed.
    assert_eq!(
        generated_nodes(&w),
        [
            "billing/api/client.gen.go oapi-codegen",
            "web/src/api/orders.ts orval"
        ]
    );
    let (total, parsed): (i64, i64) = ix
        .conn
        .query_row(
            "SELECT files_total, files_parsed FROM run ORDER BY id DESC LIMIT 1",
            [],
            |r| Ok((r.get(0)?, r.get(1)?)),
        )
        .unwrap();
    assert_eq!(total, parsed, "a generated file is not a gap");
}

#[test]
fn a_regenerated_client_with_new_function_names_keeps_the_link() {
    let d = tempfile::tempdir().unwrap();
    let mut f = fixture(d.path());
    let w = workspace(&f, &d.path().join("ws"));
    let mut cache = FactCache::open(&d.path().join("facts.db")).unwrap();
    run(&w, &mut cache);
    let before = links(&w);

    // The generator now names the function after something else, and the caller follows.
    f.write("web/src/api/orders.ts", &orval("fetchOrder"));
    f.write("web/src/page.ts", &page("fetchOrder"));
    f.commit("web: regenerate the client");
    run(&w, &mut cache);

    assert_eq!(links(&w), before, "same link, same interval: no gap");
    let a = aliases(&w);
    assert!(
        a.contains(&"getOrder get /orders/{id} 1-2".to_owned()),
        "{a:?}"
    );
    assert!(
        a.contains(&"fetchOrder get /orders/{id} 2-open".to_owned()),
        "{a:?}"
    );

    // A fresh index of the same history says the same.
    let d2 = tempfile::tempdir().unwrap();
    let w2 = workspace(&f, &d2.path().join("ws"));
    let mut cache2 = FactCache::open(&d2.path().join("facts.db")).unwrap();
    run(&w2, &mut cache2);
    assert_eq!(links(&w2), links(&w));
    assert_eq!(aliases(&w2), a);
}
