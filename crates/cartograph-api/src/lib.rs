//! The HTTP contract (INT-01): the route table, the envelope, the error shape, the two event streams
//! and every wire type, written once in Rust. `gen-contract` writes the OpenAPI file and the JSON
//! Schema that `lib/api/types.gen.ts` is generated from; a test fails when either is stale.
//!
//! Contract only: there is no server here.

pub mod events;
pub mod routes;
pub mod types;

use schemars::generate::SchemaSettings;
use serde_json::{Map, Value, json};

use routes::{Kind, Response, routes};

/// Bumped when a field is removed or changes meaning.
pub const SCHEMA_VERSION: u32 = 1;

/// The OpenAPI 3.1 document for every route.
pub fn openapi() -> Value {
    let mut settings = SchemaSettings::draft2020_12();
    settings.definitions_path = "#/components/schemas/".into();
    let mut g = settings.into_generator();
    let error = g.subschema_for::<types::ErrorBody>();

    let mut paths = Map::new();
    for r in routes() {
        let mut params: Vec<Value> = path_params(r.path)
            .map(|name| json!({"name": name, "in": "path", "required": true, "schema": {"type": "string"}}))
            .collect();
        params.extend(r.query.iter().map(|name| json!({"name": name, "in": "query", "required": false, "schema": {"type": "string"}})));

        let ok = match r.response {
            Response::Json(f) => json!({
                "description": "OK",
                "headers": {
                    "Cartograph-Generation": {"$ref": "#/components/headers/Cartograph-Generation"},
                    "Cartograph-State": {"$ref": "#/components/headers/Cartograph-State"},
                    "ETag": {"$ref": "#/components/headers/ETag"},
                },
                "content": {"application/json": {"schema": envelope(f(&mut g))}},
            }),
            Response::Text => {
                json!({"description": "Blob text", "content": {"text/plain": {"schema": {"type": "string"}}}})
            }
            Response::Events(f) => json!({
                "description": "Server-sent events. `event:` is the tag, `data:` the content, `id:` a sequence number.",
                "content": {"text/event-stream": {"schema": f(&mut g)}},
            }),
            Response::Empty => json!({"description": "Done"}),
        };
        let status = if matches!(r.response, Response::Empty) {
            "204"
        } else {
            "200"
        };
        let kind = match r.kind {
            Kind::Read => "read",
            Kind::Write => "write",
            Kind::Stream => "stream",
        };
        let mut op = json!({
            "operationId": operation_id(r.method, r.path),
            "summary": r.summary,
            "tags": [r.owner],
            "x-cartograph-kind": kind,
            "parameters": params,
            "responses": {status: ok, "default": {"description": "Error", "content": {"application/json": {"schema": error.clone()}}}},
        });
        if let Some(body) = r.body {
            op["requestBody"] = json!({"required": true, "content": {"application/json": {"schema": body(&mut g)}}});
        }
        let entry = paths.entry(r.path.to_owned()).or_insert_with(|| json!({}));
        entry[r.method.to_lowercase()] = op;
    }

    let schemas = g.take_definitions(true);
    json!({
        "openapi": "3.1.0",
        "info": {
            "title": "Cartograph local API",
            "version": SCHEMA_VERSION.to_string(),
            "description": "Served by `cartograph open` on 127.0.0.1 only. Every /api/* request sends Authorization: Bearer <token>. Writes also need a matching Origin and Content-Type: application/json. snake_case on the wire. Generated by `cargo run -p cartograph-api --bin gen-contract`; do not edit.",
        },
        "servers": [{"url": "http://127.0.0.1:{port}", "variables": {"port": {"default": "0"}}}],
        "security": [{"bearer": []}],
        "paths": paths,
        "components": {
            "securitySchemes": {"bearer": {"type": "http", "scheme": "bearer"}},
            "headers": {
                "Cartograph-Generation": {"description": "Index generation the answer was read from", "schema": {"type": "integer"}},
                "Cartograph-State": {"description": "IndexState of the workspace", "schema": {"type": "string"}},
                "ETag": {"description": "For If-None-Match, or If-Match on PUT …/config", "schema": {"type": "string"}},
            },
            "schemas": schemas,
        },
    })
}

/// One JSON Schema (draft-07, for json-schema-to-typescript) whose properties name every wire
/// type, so each is emitted into `lib/api/types.gen.ts`.
pub fn json_schema() -> Value {
    let mut g = SchemaSettings::draft07().into_generator();
    let mut props = Map::new();
    let mut add = |name: &str, schema: schemars::Schema| {
        props.insert(name.to_owned(), schema.to_value());
    };
    macro_rules! all {
        ($($t:ty),* $(,)?) => { $( add(stringify!($t), g.subschema_for::<$t>()); )* };
    }
    use events::*;
    use types::*;
    all!(
        ErrorBody,
        ReadParams,
        GraphParams,
        Version,
        Meta,
        WorkspaceSummary,
        Repo,
        Freshness,
        GraphSlice,
        NodeDetail,
        Node,
        Link,
        LinkDetail,
        SymbolCalls,
        SearchResult,
        Commit,
        CommitImpact,
        TimelineDensity,
        TimelineMarker,
        ImpactRequest,
        ImpactResult,
        PathResult,
        Reach,
        Contract,
        Entrypoint,
        Concept,
        CoverageRow,
        Unresolved,
        Owner,
        Rule,
        RuleViolation,
        Service,
        Environment,
        Adapter,
        Correction,
        CorrectionRequest,
        FileDiff,
        ConceptDecision,
        ConfigFile,
        ConfigWrite,
        IndexingSettings,
        JobRequest,
        Job,
        ActivityItem,
        ActivityRead,
        FsEntry,
        DiscoverRequest,
        Discovery,
        CreateWorkspace,
        CreatedWorkspace,
        Prefs,
        McpTool,
        AgentStatus,
        AgentInstall,
        RunRequest,
        AskCommand,
        Thread,
        TurnContext,
        Provider,
        ProviderWrite,
        KeyWrite,
        ProviderTest,
        Selection,
        Privacy,
        ServerEvent,
        RunEvent,
    );
    let mut names: Vec<&String> = props.keys().collect();
    names.sort();
    let names: Vec<Value> = names.into_iter().cloned().map(Value::String).collect();
    let defs = g.take_definitions(true);
    json!({
        "$schema": "http://json-schema.org/draft-07/schema#",
        "title": "CartographApi",
        "description": "Every Cartograph HTTP wire type. Generated from crates/cartograph-api; do not edit.",
        "type": "object",
        "properties": props,
        "required": names,
        "additionalProperties": false,
        "definitions": defs,
    })
}

/// The envelope around a route's data, inline so each route's `data` is typed.
fn envelope(data: schemars::Schema) -> Value {
    json!({
        "type": "object",
        "required": ["schema", "generation", "data", "next_cursor", "truncated"],
        "properties": {
            "schema": {"type": "integer", "const": SCHEMA_VERSION},
            "generation": {"type": "integer", "minimum": 0},
            "data": data,
            "next_cursor": {"type": ["string", "null"]},
            "truncated": {"type": "boolean"},
        },
    })
}

fn path_params(path: &str) -> impl Iterator<Item = &str> {
    path.split('/')
        .filter_map(|seg| seg.strip_prefix('{')?.strip_suffix('}'))
}

fn operation_id(method: &str, path: &str) -> String {
    let mut id = method.to_lowercase();
    for seg in path.trim_start_matches("/api/").split(['/', '-']) {
        let seg = seg.trim_start_matches('{').trim_end_matches('}');
        if seg.is_empty() || seg == "v1" || seg == "w" {
            continue;
        }
        let mut c = seg.chars();
        if let Some(f) = c.next() {
            id.push(f.to_ascii_uppercase());
            id.extend(c);
        }
    }
    id
}

/// Pretty JSON with a trailing newline, as checked in.
pub fn render(v: &Value) -> String {
    let mut s = serde_json::to_string_pretty(&sorted(v)).expect("JSON values always serialise");
    s.push('\n');
    s
}

/// `v` with every object's keys in order. serde_json keeps insertion order when any crate in the
/// build enables its `preserve_order` feature (oxc_resolver does), so the output must not rely on
/// the map type.
fn sorted(v: &Value) -> Value {
    match v {
        Value::Object(m) => {
            let mut keys: Vec<&String> = m.keys().collect();
            keys.sort();
            Value::Object(
                keys.into_iter()
                    .map(|k| (k.clone(), sorted(&m[k])))
                    .collect(),
            )
        }
        Value::Array(a) => Value::Array(a.iter().map(sorted).collect()),
        other => other.clone(),
    }
}

/// Where the generated files live, relative to the repository root.
pub const OPENAPI_PATH: &str = "crates/cartograph-api/openapi.json";
pub const SCHEMA_PATH: &str = "crates/cartograph-api/schema.json";

#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::HashSet;

    fn repo_file(rel: &str) -> String {
        let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
        // A Windows checkout may still carry CRLF; the generator writes LF.
        std::fs::read_to_string(root.join(rel))
            .unwrap_or_default()
            .replace("\r\n", "\n")
    }

    #[test]
    fn checked_in_contract_is_current() {
        assert!(
            repo_file(OPENAPI_PATH) == render(&openapi())
                && repo_file(SCHEMA_PATH) == render(&json_schema()),
            "the contract changed: run `cargo run -p cartograph-api --bin gen-contract` and `pnpm gen:types`"
        );
    }

    #[test]
    fn routes_are_unique_and_versioned() {
        let mut seen = HashSet::new();
        for r in routes() {
            assert!(
                seen.insert((r.method, r.path)),
                "duplicate route {} {}",
                r.method,
                r.path
            );
            assert!(
                r.path == "/api/version" || r.path.starts_with("/api/v1/"),
                "{} is outside /api/v1",
                r.path
            );
        }
    }

    #[test]
    fn the_write_list_is_closed() {
        // Only writes and the documented read-only POSTs carry a body; GET and DELETE never do.
        for r in routes() {
            if matches!(r.method, "GET" | "DELETE") {
                assert!(r.body.is_none(), "{} {} has a body", r.method, r.path);
            }
            if matches!(r.method, "PUT" | "DELETE") {
                assert_eq!(
                    r.kind,
                    Kind::Write,
                    "{} {} changes state but isn't a write",
                    r.method,
                    r.path
                );
            }
        }
        let writes = routes().iter().filter(|r| r.kind == Kind::Write).count();
        assert_eq!(
            writes, 21,
            "the write list changed: update the Interfaces section and HD-11"
        );
    }

    #[test]
    fn wire_names_are_snake_case() {
        let text = render(&openapi());
        for bad in [
            "\"keySaved\"",
            "\"indexedCommit\"",
            "\"builtAt\"",
            "\"needs-migrate\"",
            "\"name-match\"",
            "\"fanIn\"",
        ] {
            assert!(
                !text.contains(bad),
                "{bad} is camelCase or kebab-case on the wire"
            );
        }
    }
}
