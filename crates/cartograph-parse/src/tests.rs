#[test]
fn manifests_keep_resolution_fields_and_read_jsonc() {
    let (e, k) = extractor_for("p/package.json").unwrap();
    let f = e.extract(
        k,
        br#"{"name":"p","version":"1.0.0","exports":{".":"./src/index.ts"},"dependencies":{"b":"1","a":"2"}}"#,
    );
    assert_eq!(
        manifest::resolution_json(f.facts(), true),
        r#"{"exports":{".":"./src/index.ts"},"name":"p"}"#
    );
    let bumped = e.extract(
        k,
        br#"{"version":"2.0.0","name":"p","exports":{".":"./src/index.ts"}}"#,
    );
    assert_eq!(
        manifest::resolution_json(f.facts(), true),
        manifest::resolution_json(bumped.facts(), true),
        "a version bump changes no resolution field"
    );
    let (e, k) = extractor_for("tsconfig.json").unwrap();
    let f = e.extract(
        k,
        b"{\n // comment\n \"compilerOptions\": {\"baseUrl\": \".\",},\n}",
    );
    assert_eq!(
        manifest::resolution_json(f.facts(), false),
        r#"{"compilerOptions":{"baseUrl":"."}}"#
    );
}

#[test]
fn golden_facts_for_a_fixture_folder() {
    let folder = [
        (
            "src/index.ts",
            "import { a } from './a';\nexport * from './b';\nimport type { T } from '@scope/types';\nconst m = await import('./lazy');\n",
        ),
        (
            "src/a.tsx",
            "import React from 'react';\nexport const A = () => <div>{require(dynamic)}</div>;\n",
        ),
        (
            "lib/old.cjs",
            "const fs = require('node:fs');\nmodule.exports = require(\"./impl\");\n",
        ),
        (
            "package.json",
            "{\"name\":\"fixture\",\"main\":\"src/index.ts\",\"workspaces\":[\"packages/*\"]}",
        ),
        (
            "tsconfig.json",
            "{\"extends\":\"./tsconfig.base.json\",\"compilerOptions\":{\"paths\":{\"@/*\":[\"src/*\"]}}}",
        ),
    ];
    let mut out = String::new();
    for (path, src) in folder {
        let (e, k) = extractor_for(path).unwrap();
        out += &format!("{path} ({k})\n");
        for f in e.extract(k, src.as_bytes()).facts() {
            out += &format!("  {f:?}\n");
        }
    }
    insta::assert_snapshot!(out);
}

proptest! {
    #![proptest_config(ProptestConfig::with_cases(256))]
    /// The same bytes always give the same encoded facts, and no input panics an extractor (the
    /// fuzz target, as a property; ponytail: cargo-fuzz needs nightly and arrives with HD-06).
    #[test]
    fn same_bytes_same_encoding(bytes in proptest::collection::vec(any::<u8>(), 0..2048), which in 0usize..5) {
        let path = ["a.ts", "a.tsx", "a.js", "package.json", "tsconfig.json"][which];
        let (e, k) = extractor_for(path).unwrap();
        let a = e.extract(k, &bytes).encode();
        prop_assert_eq!(&a, &e.extract(k, &bytes).encode());
        prop_assert!(BlobFacts::decode(&a).is_some());
    }

    #[test]
    fn import_like_text_never_panics(src in "(import|export|require|from|\\(|\\)|'|\"|`|\\$\\{|\\}|\\{|;| |\\n|\\./a|x|type|\\*)*") {
        for path in ["a.ts", "a.tsx", "a.js"] {
            let (e, k) = extractor_for(path).unwrap();
            let _ = e.extract(k, src.as_bytes());
        }
    }
}
