use super::*;
use proptest::prelude::*;

fn specs(path: &str, src: &str) -> Vec<(String, ImportStyle)> {
    let (e, k) = extractor_for(path).unwrap();
    e.extract(k, src.as_bytes())
        .facts()
        .iter()
        .filter_map(|f| match f {
            Fact::Import { spec, style, .. } => Some((spec.clone(), *style)),
            _ => None,
        })
        .collect()
}

fn one(path: &str, src: &str) -> (String, ImportStyle) {
    let got = specs(path, src);
    assert_eq!(got.len(), 1, "{src}: {got:?}");
    got[0].clone()
}

#[test]
fn every_import_form() {
    use ImportStyle::*;
    let s = |x: &str| x.to_owned();
    assert_eq!(one("a.ts", "import a from './a';"), (s("./a"), Esm));
    assert_eq!(one("a.ts", "import './side';"), (s("./side"), Esm));
    assert_eq!(one("a.ts", "import * as n from \"n\";"), (s("n"), Esm));
    assert_eq!(
        one("a.ts", "import type { T } from './t';"),
        (s("./t"), TypeOnly)
    );
    assert_eq!(one("a.ts", "export * from '../b';"), (s("../b"), Reexport));
    assert_eq!(
        one("a.ts", "export { x } from './x';"),
        (s("./x"), Reexport)
    );
    assert_eq!(
        one("a.ts", "export type { T } from './t';"),
        (s("./t"), TypeOnly)
    );
    assert_eq!(one("a.js", "const c = require('c');"), (s("c"), Cjs));
    assert_eq!(one("a.ts", "import fs = require('fs');"), (s("fs"), Cjs));
    assert_eq!(one("a.mjs", "await import('./d');"), (s("./d"), Dynamic));
    assert_eq!(
        one("a.tsx", "const D = lazy(() => import(`./page`)); <D/>;"),
        (s("./page"), Dynamic)
    );
    assert_eq!(
        one(
            "a.jsx",
            "import R from 'react'; export const X = () => <div/>;"
        ),
        (s("react"), Esm)
    );
}

#[test]
fn computed_arguments_are_kept_for_coverage() {
    let (e, k) = extractor_for("a.ts").unwrap();
    let f = e.extract(k, b"require(name); import(`./x/${y}`);");
    assert_eq!(f.facts().len(), 2);
    assert!(
        f.facts()
            .iter()
            .all(|f| matches!(f, Fact::DynamicUnresolved { .. }))
    );
}

#[test]
fn strings_and_comments_are_not_imports() {
    let src = "// import a from './a'\nconst s = \"require('b')\";\n/* export * from './c' */\n";
    assert!(specs("a.ts", src).is_empty());
}

#[test]
fn skip_rules() {
    let (e, k) = extractor_for("a.ts").unwrap();
    let big = "x".repeat(MAX_BLOB_BYTES as usize + 1);
    assert_eq!(
        e.extract(k, big.as_bytes()),
        BlobFacts::Skipped(SkipReason::TooLarge)
    );
    assert_eq!(
        e.extract(k, b"import\0"),
        BlobFacts::Skipped(SkipReason::Binary)
    );
    assert_eq!(
        e.extract(
            k,
            b"version https://git-lfs.github.com/spec/v1\noid sha256:00\n"
        ),
        BlobFacts::Skipped(SkipReason::LfsPointer)
    );
    assert_eq!(
        e.extract(k, b"// @generated by a tool\nimport a from './a';"),
        BlobFacts::Skipped(SkipReason::Generated)
    );
}

